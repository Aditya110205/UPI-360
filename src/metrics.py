"""Generates KEY_METRICS.md and RESUME_BULLETS.md from the database and ml outputs. Run after models.py."""
import json
from pathlib import Path
import duckdb, numpy as np, pandas as pd
ROOT = Path(__file__).resolve().parent.parent
P = json.loads((ROOT / "reports" / "dashboard_data.json").read_text())
d = pd.DataFrame(P["months"]); d["d"] = pd.to_datetime(d["d"]); d = d.set_index("d")
v = d.v; yrs = (v.index[-1] - v.index[0]).days / 365.25
cagr = ((v.iloc[-1] / v.iloc[0]) ** (1 / yrs) - 1) * 100
yoy = v.pct_change(12) * 100
ho = P["holdout"]; fs = P["festive"]; f = P["forecast"]
peak_d = v.idxmax()
n_sql = len([s for s in (ROOT / "sql" / "queries.sql").read_text().split(";") if "select" in s.lower()])
tk0, tk1 = d.t.iloc[0], d.t.iloc[-1]
bk0, bk1 = d.b.iloc[0], d.b.iloc[-1]
season = pd.Series(P["season"]); mn = {1:"Jan",2:"Feb",3:"Mar",4:"Apr",5:"May",6:"Jun",7:"Jul",8:"Aug",9:"Sep",10:"Oct",11:"Nov",12:"Dec"}
hi_m, lo_m = mn[int(season.idxmax())], mn[int(season.idxmin())]
flag = [a for a in P["anomalies"] if a["f"]]
fl = ", ".join(sorted(a["d"] for a in flag))
q = lambda x: f"{x:,.0f}"
rows = [
 ("Months analysed", f"{len(d)} ({v.index[0]:%b %Y} to {v.index[-1]:%b %Y})", "COUNT(*) FROM upi_monthly"),
 ("Volume, first month", f"{v.iloc[0]:.2f}M txns ({v.index[0]:%b %Y})", "upi_monthly, first row"),
 ("Volume, latest month", f"{q(v.iloc[-1])}M txns ({v.index[-1]:%b %Y})", "upi_monthly, last row"),
 ("Peak month", f"{q(v.max())}M txns ({peak_d:%b %Y})", "MAX(volume_mn)"),
 ("CAGR, volume", f"{cagr:.1f}% per year over {yrs:.1f} years", "(last/first)^(1/years)-1"),
 ("Total volume processed", f"{q(v.sum())}M txns", "SUM(volume_mn)"),
 ("YoY growth, latest month", f"{yoy.iloc[-1]:.1f}% ({v.index[-1]:%b %Y} vs {v.index[-13]:%b %Y})", "pct_change(12)"),
 ("YoY growth, last 12 months avg", f"{yoy.iloc[-12:].mean():.1f}%", "mean of last 12 YoY values"),
 ("YoY growth, 2019 avg", f"{yoy['2019'].mean():.1f}%", "mean of 2019 YoY values"),
 ("Banks live, first / latest", f"{bk0} / {bk1} (x{bk1/bk0:.1f})", "num_banks"),
 ("Avg ticket size, first month", f"Rs {q(tk0)}", "value_cr*1e7/(volume_mn*1e6)"),
 ("Avg ticket size, latest month", f"Rs {q(tk1)} ({(tk1/tk0-1)*100:.0f}% vs first month)", "same formula"),
 ("Value processed, latest month", f"Rs {d.c.iloc[-1]/1e5:.1f} lakh crore", "value_cr / 1e5"),
 ("Strongest seasonal month", f"{hi_m} (index {season.max():.3f} vs 12-month average)", "ratio to centred 12m MA"),
 ("Weakest seasonal month", f"{lo_m} (index {season.min():.3f})", "ratio to centred 12m MA"),
 ("Oct-Dec vs other months (detrended)", f"{fs['festive_mean']:.3f} vs {fs['other_mean']:.3f}, Mann-Whitney p {'< 0.001' if fs['p'] < 0.001 else f'= {fs['p']:.3f}'}", "scipy mannwhitneyu"),
 ("Holdout window", f"{ho['months'][0]} to {ho['months'][-1]} (6 months)", "src/models.py"),
 ("Holdout MAPE, naive", f"{ho['mape']['naive']:.2f}%", "src/models.py"),
 ("Holdout MAPE, drift (12m slope)", f"{ho['mape']['drift_12m']:.2f}%", "src/models.py"),
 ("Holdout MAPE, damped ETS (log)", f"{ho['mape']['ets_damped_log']:.2f}%", "src/models.py"),
 ("Forecast, " + f[0]["d"], f"{q(f[0]['f'])}M (80% band {q(f[0]['lo'])} to {q(f[0]['hi'])})", "best model refit on all data"),
 ("Forecast, " + f[-1]["d"], f"{q(f[-1]['f'])}M (80% band {q(f[-1]['lo'])} to {q(f[-1]['hi'])})", "best model refit on all data"),
 ("Growth phases", "; ".join(f"{p['name']}: {p['months']} months ({p['from']} to {p['to']})" for p in P["phases"]), "KMeans k=3 on log volume"),
 ("Anomalies flagged", f"{len(flag)} of {len(P['anomalies'])} scored months: {fl}", "IsolationForest, contamination 6%"),
]
md = ["# KEY_METRICS: UPI 360", "", "Every number below is generated by `src/models.py` and `src/metrics.py` from `data/upi.duckdb`. Do not edit by hand; re-run the scripts.", "",
      "| Metric | Value | Source |", "|---|---|---|", *[f"| {a} | {b} | `{c}` |" for a, b, c in rows], "",
      f"Best holdout model: **{ho['best']}**. Intervals are approximate (recent month-on-month volatility). ",
      "Data: UPI product statistics (NPCI), aggregated monthly. There is no transaction-level data, so behaviour findings describe market-level patterns, not individual users.", ""]
(ROOT / "KEY_METRICS.md").write_text("\n".join(md))
best = ho["best"]; bm = ho["mape"][best]; nv = ho["mape"]["naive"]
rb = f"""# RESUME_BULLETS: UPI 360

Every figure comes from KEY_METRICS.md. Check each one against the dashboard before use.

## Resume bullets

- Built an end-to-end analytics pipeline on {len(d)} months of NPCI UPI statistics ({v.index[0]:%b %Y} to {v.index[-1]:%b %Y}): pandas cleaning, a DuckDB warehouse and {n_sql} SQL queries using CTEs and window functions, surfacing a {cagr:.0f}% volume CAGR and growth slowing from {yoy['2019'].mean():.0f}% (2019 avg YoY) to {yoy.iloc[-12:].mean():.0f}% (last 12 months).
- Found that average UPI ticket size fell {abs((tk1/tk0-1)*100):.0f}% (Rs {q(tk0)} to Rs {q(tk1)}) while monthly volume reached {q(v.iloc[-1])}M transactions, showing growth driven by small payments.
- Benchmarked three forecasting models on a 6-month holdout; {best} reached {bm:.2f}% MAPE against {nv:.2f}% for a naive baseline, then produced a 6-month forecast with an uncertainty band.
- Detrended the series to test seasonality: Oct-Dec runs {(fs['festive_mean']/fs['other_mean']-1)*100:.1f}% above the rest of the year (Mann-Whitney {'p < 0.001' if fs['p'] < 0.001 else f"p = {fs['p']:.3f}"}); naive month averages hid this because of the growth trend.
- Used Isolation Forest on detrended growth and ticket size to flag {len(flag)} unusual months, including the April and May 2020 lockdown dip and rebound.
- Shipped an interactive 4-view dashboard (market, behaviour, risk, ask-the-data) with date-range filters, deployed publicly.

## LinkedIn summary

UPI 360 analyses {len(d)} months of India's UPI statistics with SQL, Python and DuckDB: growth, seasonality, ticket-size trends, a holdout-tested forecast and anomaly detection, delivered as an interactive dashboard.
"""
(ROOT / "RESUME_BULLETS.md").write_text(rb)
print(open(ROOT/"KEY_METRICS.md").read()); print(rb[:1800])